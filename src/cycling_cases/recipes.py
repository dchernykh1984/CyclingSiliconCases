E840_PART = (60.0, 103.59, 17.0)
"""Габарит той детали раскладки, в которую пакуется прибор, мм.

В файле шесть тел: вынос, два полухомута, две прокладки и собственно
чехол. Ищем чехол по размеру, а не по номеру тела: если исходник
однажды заменят, сборка упадёт с понятной ошибкой вместо того, чтобы
молча положить в релиз хомут.
"""

E840_CAP = 4.0
"""Высота прописной надписи на 840, мм.

Нос — скруглённый гребень без единой плоской площадки: от макушки к
краям строки поверхность уходит назад на 3 мм, а по вертикали радиус
около 3 мм. Надпись поэтому лежит по поверхности и заворачивается за
гребень; на углах крайних букв поверхность наклонена к площадке на
47°, и видимая высота рельефа там падает с 0.8 до 0.55 мм. Это
приемлемо, а высота буквы 4 мм даёт стойку 0.92 мм — как на 830, то
есть два периметра сопла 0.4 мм.
"""

E840_WINDOW_Z = (-2.3, 6.4)
"""Пояс кнопок по высоте, мм — в нём режутся все окна.

Низ взят у автора исходника: единственное сквозное окно, которое у
чехла уже было, начинается на −2.3. Все семь кнопок Edge 840 лежат
между 0.0 и 4.8 — пояс накрывает их с запасом в два миллиметра снизу
и полтора сверху.

Верх на 0.3 мм ниже, чем у автора (у него 6.7). Причина не в кнопках,
а в сетке: карманы кончаются сверху ровно на 6.7, и рез по той же
плоскости совпал бы с гранью кармана — вместо четырёх рёбер с
самокасанием, которые есть в исходнике, их стало бы шестнадцать.
Полоска над окном от этого только прочнее: её верхние 2.8 мм идут в
полную толщину стенки.
"""

E840_BUTTON_POCKETS: dict[int, tuple[tuple[float, float], ...]] = {
    -1: ((50.5, 78.0), (83.5, 98.0)),
    +1: ((50.5, 65.0), (83.5, 98.0)),
}
"""Где у Edge 840 боковые кнопки — по разметке самого исходника, мм.

Точных координат кнопок нет ни в мануале, ни в обзорах, но автор модели
их знал: в полости чехла размечены карманы, где стенка утончена с 1.75
до 0.75 мм. Слева таких карманов два — 50.5…78.0 (27.5 мм, под пару
«вверх/вниз») и 83.5…98.0 (14.5 мм, под питание); справа тоже два —
50.5…65.0 («назад») и 83.5…98.0 («выбор»). Три кнопки слева и две
справа — ровно столько их у Edge 840, и верхняя пара приходится на
носовой конец, то есть на верх прибора.

Мембрана 0.75 мм в TPU продавливается пальцем, но на неё нельзя
положиться: за неё цепляются, и именно тонкая стенка рвётся первой.
Поэтому карманы прорезаются насквозь — по их собственным границам, так
что между окнами остаются рёбра исходника в полную толщину: 6.5 мм
перед первым окном, 5.5 мм между окнами слева, 18.5 мм справа и 9 мм
до носа.
"""

E840_POCKET_OVERCUT = 0.4
"""На сколько окно выходит за границу кармана, мм.

Если резать ровно по границе, плоскость реза совпадает со ступенькой
кармана: сетка получается с самокасаниями, а по краю окна остаётся
лезвие толщиной 0.75 мм. Зайдя на 0.4 мм в ребро, получаем и чистый
рез, и кромку окна в полной толщине стенки.
"""

E840_SIDE_WALL: dict[int, tuple[float, float]] = {
    -1: (-130.0, -115.0),
    +1: (-65.0, -50.0),
}
"""Докуда резать по X, чтобы снять только свой бок, мм.

Левая стенка лежит между -120.0 и -118.25, правая между -61.75 и -60.0.
Резак на всю ширину снял бы оба бока сразу, а окна у них разные.
"""

E840_REAR_BUTTONS: tuple[tuple[float, float], ...] = ((-110.2, -107.1), (-72.7, -70.1))
"""Кнопки lap и start/stop на заднем торце — по модели прибора, мм.

Разметки под них автор исходника не оставил: торец у него сплошной,
толщиной 4.5 мм. Зато есть модель самого Edge 840, и кнопки на ней
находятся замером (`devices.buttons`). Они сидят не по центру торца,
а на завале углов — в 18.7 мм от середины в обе стороны, и по
абсолютной высоте ниже, чем середина того же торца.

Прежнее окно шириной 36 мм по центру торца било мимо обеих: от левой
кнопки в него попадало 0.5 мм из 3.0, от правой — 0.5 из 2.5.
"""

E840_REAR_MARGIN = 2.0
"""Запас вокруг кнопки нижнего торца, мм.

Два окна по кнопкам вместо одного широкого: между ними остаётся
30 мм сплошного торца, а по краям ещё по шесть. Широкое окно снимало
торец в поясе кнопок целиком, и рамка держалась только полосками
сверху и снизу.
"""

E840_CENTRE = (90.0, -75.5, 7.8)
"""Сдвиг детали из раскладки в начало координат, мм.

Деталь лежала в общем файле сбоку от выноса. В релизе она едет одна,
и удобнее, когда она стоит на плоскости z=0 и центрирована — так её
не приходится искать по столу слайсера.
"""


def pick_case(source: Triangles, size: tuple[float, float, float], slack: float = 1.0) -> Triangles:
    """Найти в раскладке тело нужного габарита."""
    wanted = np.asarray(size)
    for part in parts(source):
        if np.all(np.abs(part.size - wanted) <= slack):
            return part.triangles
    found = "; ".join(f"{np.round(part.size, 2)}" for part in parts(source))
    raise LookupError(f"в раскладке нет тела {wanted} (± {slack}); есть {found}")


def garmin_840(source: Triangles) -> Manifold:
    """Чехол Edge 840: только сам чехол, окна под кнопки и надпись.

    Исходник — раскладка на стол: вынос, хомуты, прокладки и чехол.
    Берём из неё одно тело — бампер-рамку с полостью 58.5×87.5 мм, в
    которую и пакуется прибор. Рамка открыта и сверху, и снизу: снизу
    к прибору должно подходить крепление Garmin, сверху остаётся экран.

    Дальше прорезаем то, что у исходника было закрыто: боковые кнопки
    (автор оставил под ними мембрану 0.75 мм) и кнопки нижнего торца
    (там была сплошная стенка 4.5 мм).
    """
    case = pick_case(source, E840_PART)
    body = solid.from_triangles(case)

    low, high = E840_WINDOW_Z
    for sign, pockets in E840_BUTTON_POCKETS.items():
        near, far = E840_SIDE_WALL[sign]
        for start, finish in pockets:
            window = solid.rounded_rectangle(
                (start - E840_POCKET_OVERCUT, low),
                (finish + E840_POCKET_OVERCUT, high),
                radius=2.0,
            )
            body = body - solid.prism(window, near, far, axis=0)

    for start, finish in E840_REAR_BUTTONS:
        rear = solid.rounded_rectangle(
            (start - E840_REAR_MARGIN, low),
            (finish + E840_REAR_MARGIN, high),
            radius=2.0,
        )
        body = body - solid.prism(rear, 18.0, 31.0, axis=1)

    nose = panel.measure(
        case,
        axis=1,
        sign=1,
        origin=(-90.0, 115.0, 1.0),
        u_range=(-17.8, 17.8),
        v_range=(-2.6, 2.6),
    )
    body = body + nose.emboss(_lettering(E840_CAP), RELIEF, SINK)
    return body.translate(list(E840_CENTRE))
