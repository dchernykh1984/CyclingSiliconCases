"""Что именно мы делаем с каждым чехлом — и почему именно так.

Здесь живут все числа. Они не выдуманы: каждое снято с исходной сетки
лучами (`mesh.ray_distances`) или её срезами, а рядом сказано, из чего
оно следует. Проверка чисел — в `tests/`, и она считает по готовой
детали, а не по этому файлу.

Общая система координат у обеих моделей одинакова: Z — от спинки к
экрану, +Y — вперёд по ходу движения (носовая стенка), -Y — к
велосипедисту (там у обоих приборов кнопки нижнего торца), -X — левый
бок прибора, если смотреть на экран.
"""

from __future__ import annotations

import numpy as np
from manifold3d import Manifold

from . import panel, solid
from .lettering import Lettering, line
from .mesh import Triangles, parts

SLOGAN = "UBT 8 YEARS"
RELIEF = 0.8
"""Высота выпуклых букв, мм.

Выпуклость, а не гравировка: TPU печатают медленно и с прижимом, и
углубление в 0.4 мм слайсер на наружной стенке просто затирает
периметром. Наружу же буква растёт свободно. 0.8 мм — четыре слоя по
0.2 мм: видно и на ощупь, и глазом, и не цепляется за карман.
"""

SINK = 0.6
"""На сколько буквы утоплены в стенку, чтобы слиться с ней в одно тело."""


def _lettering(cap_height: float) -> Lettering:
    return line(SLOGAN, cap_height).centred()


# --------------------------------------------------------------------------
# Garmin Edge 830
# --------------------------------------------------------------------------

E830_CAP = 4.0
"""Высота прописной надписи на 830, мм.

Передняя стенка держит плоскость в пределах x ±17.5: дальше начинается
скругление угла, и поверхность уходит назад на 2 мм за четыре
миллиметра. Строка «UBT 8 YEARS» при высоте 4 мм занимает 34.7 мм —
ровно этот участок. Стойка буквы выходит 0.92 мм: два периметра
сопла 0.4 мм.
"""

E830_TEXT_Z = 17.2
"""Середина строки по высоте.

Выше 15.5 мм передняя стенка вертикальна, кромка чехла на 20.6. Строка
высотой 4 мм с серединой на 17.2 укладывается в 15.2…19.2 — целиком в
вертикальную часть, с запасом 1.4 мм до кромки.
"""

E830_LIP_FLOOR = 17.9
E830_LIP_PEAK = 19.8
E830_LIP_TOP = 20.55
"""Профиль удерживающей губы по высоте, мм.

Прибор лежит на дне чехла (верх дна 2.05) и имеет корпус без бобышки
крепления примерно 16.5 мм — значит его лицевая грань приходится на
18.5. Штатный загиб на заднем торце подтверждает: его нижняя кромка
как раз там. Губа начинается чуть ниже (17.9), выходит на полную
высоту к 19.8 и уходит обратно в стенку к 20.55, не поднимаясь над
кромкой. Наклон нижней грани 34–45° — печатается без поддержек.
"""

E830_GRAB = 0.8
"""На сколько губа заходит на лицевую рамку прибора, мм.

Меньше — прибор выскакивает, больше — чехол не натянуть: по ширине
полость 50.6 мм при приборе 50 мм, и две губы по 0.8 мм оставляют
натяг 1.0 мм. TPU такой натяг берёт руками.
"""


def _bead(
    axis: int,
    sign: int,
    back: float,
    tip: float,
    run: tuple[float, float],
    taper: float = 3.0,
) -> Manifold:
    """Валик губы вдоль стенки: треугольный профиль со сходящими концами.

    `back` — координата спрятанной в стенку спинки валика, `tip` — самая
    внутренняя точка. Концы сводятся на нет за `taper`: резко
    обрывающийся валик в TPU работает как надрез.
    """
    profile = solid.polygon([(back, E830_LIP_FLOOR), (tip, E830_LIP_PEAK), (back, E830_LIP_TOP)])
    run_axis = 1 - axis
    body = solid.prism(profile, run[0] - taper - 1.0, run[1] + taper + 1.0, run_axis)

    outer = back + sign * 1.0
    inner = tip - sign * 1.0
    if axis == 0:
        corners = [
            (outer, run[0] - taper),
            (inner, run[0] + taper),
            (inner, run[1] - taper),
            (outer, run[1] + taper),
        ]
    else:
        corners = [
            (run[0] - taper, outer),
            (run[0] + taper, inner),
            (run[1] - taper, inner),
            (run[1] + taper, outer),
        ]
    limit = solid.prism(solid.polygon(corners), E830_LIP_FLOOR - 1.0, E830_LIP_TOP + 1.0, axis=2)
    return body ^ limit


def garmin_830(source: Triangles) -> Manifold:
    """Чехол Edge 830: выпуклая надпись спереди и губы удержания.

    Исходник — цельный чехол-ванночка: дно с круглым окном под
    крепление, открытый верх, окно 15×9 мм на левом боку под кнопку
    питания и окно 44×10 мм по всему заднему торцу под кнопки lap и
    start/stop. Кнопки, стало быть, уже доступны все три — резать
    нечего. Не хватало другого: загиб, удерживающий прибор, был только
    на заднем торце, и чехол держался в основном креплением Garmin.
    """
    body = solid.from_triangles(source)

    front = panel.measure(
        source,
        axis=1,
        sign=1,
        origin=(0.0, 0.0, E830_TEXT_Z),
        u_range=(-17.8, 17.8),
        v_range=(-2.6, 2.6),
    )
    body = body + front.emboss(_lettering(E830_CAP), RELIEF, SINK)

    # Полость: по X от -24.86 до 25.75, спереди до 41.80 — замер лучами
    # по срезу z = 10…14, где стенки уже вертикальны.
    body = body + _bead(0, -1, back=-25.96, tip=-24.86 + E830_GRAB, run=(-24.0, 28.0))
    body = body + _bead(0, 1, back=26.85, tip=25.75 - E830_GRAB, run=(-24.0, 28.0))
    body = body + _bead(1, 1, back=42.29, tip=41.80 - E830_GRAB, run=(-14.0, 14.0))
    return body


